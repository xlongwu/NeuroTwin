"""Exploratory fixed profile reference and nonoverlapping within-scan profile segments."""
import argparse,json,time
from pathlib import Path
import numpy as np,torch
from analysis.h18_data import calibrate_raw
from analysis.h18_probes import GROUPS,ROOT
from analysis.individual_pilot import digest
from inference_twin import TwinSession,load_raw_series


def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--group',choices=GROUPS,required=True);p.add_argument('--device',default='cpu')
 p.add_argument('--baseline',type=Path,required=True);p.add_argument('--output',type=Path,required=True);p.add_argument('--limit',type=int,default=0)
 a=p.parse_args();ckpt,split,condfile=GROUPS[a.group];ids=json.loads((ROOT/'data'/split).read_text())['test']
 base=a.baseline/a.group;man=json.loads((base/'数据清单.json').read_text())
 if man['subjects']!=ids or man['checkpoint_sha256']!=digest(ROOT/ckpt):raise ValueError('基线来源不匹配')
 selected=ids[:a.limit] if a.limit else ids;dst=a.output/a.group;dst.mkdir(parents=True,exist_ok=True)
 proto={'group':a.group,'checkpoint_sha256':digest(ROOT/ckpt),'baseline_manifest_sha256':digest(base/'数据清单.json'),
        'subjects':selected,'reference':'fixed profile generated by model.calibrate_profile on a zero 32-TR calibration signal',
        'segments':'nonoverlapping 32 TR windows with original prefix calibration; later windows exploratory and distribution shifted',
        'forward':'actual history and conditions, compare original profile to fixed reference; H1',
        'device':a.device,'torch':torch.__version__}
 path=dst/'数据清单.json'
 if path.exists():
  if json.loads(path.read_text())!=proto:raise ValueError('清单不一致')
 else:path.write_text(json.dumps(proto,ensure_ascii=False,indent=2)+'\n')
 session=TwinSession(str(ROOT/ckpt),device=a.device,condition_file=condfile);model=session.model;start=time.perf_counter()
 with torch.inference_mode():
  ref=model.calibrate_profile(torch.zeros((1,116,1,32),dtype=torch.float32,device=a.device))
  for i,sid in enumerate(selected):
   path=dst/f'{sid}.npz'
   if path.exists():continue
   with np.load(base/f'{sid}.npz') as z:
    anchors=z['cutoff'].copy();cached=z['prediction'].copy();true=z['true'].copy();orig_profile=z['profile'].copy()
   raw=load_raw_series(ROOT/f'data/Raw/{a.group.upper()}/ROISignals_{sid}.mat',116);series=calibrate_raw(raw,32)
   x=torch.from_numpy(np.stack([series[t-63:t+1].T for t in anchors]).copy())[:,:,None,:].to(a.device)
   cal=torch.from_numpy(series[:32].T.copy())[None,:,None,:].to(a.device);profile=model.calibrate_profile(cal);cond=session.condition_for(sid);n=len(anchors)
   expanded={k:v.expand(n,*v.shape[1:]) for k,v in cond.items()}
   _,aux=model(x,sc_matrix=None,calibration_bold=cal.expand(n,-1,-1,-1),profile=ref.expand(n,-1),condition=expanded,dynamics_horizon=1)
   refpred=aux['dynamics_pred'][:,:,0].cpu().numpy()
   starts=np.arange(0,len(series)-31,32);segments=torch.from_numpy(np.stack([series[t:t+32].T for t in starts]).copy())[:,:,None,:].to(a.device)
   seg_profiles=model.calibrate_profile(segments).cpu().numpy()
   if not np.isfinite(refpred).all() or not np.isfinite(seg_profiles).all():raise ValueError(f'{sid}: 非有限输出')
   temp=dst/f'.{sid}.tmp.npz';np.savez_compressed(temp,cutoff=anchors,baseline=cached,reference_prediction=refpred,true=true,
     original_profile=profile[0].cpu().numpy(),cached_profile=orig_profile,reference_profile=ref[0].cpu().numpy(),
     segment_start=starts,segment_profile=seg_profiles)
   temp.replace(path);print(f'{a.group} {i+1}/{len(selected)} elapsed={time.perf_counter()-start:.1f}s',flush=True)

if __name__=='__main__':main()
